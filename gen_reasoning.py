# -*- coding: utf-8 -*-
"""生成《注塑品质不良 · 要因拆解逻辑（一次~四次要因全清单）》

数据源 = gen_fishbone.py 的 CATS，改数据后重跑本脚本即可同步文档。
层级归属一律以现有鱼骨图为准（一次=大骨 / 二次=中骨 / 三次=小骨 / 四次=小小骨）。

用法: python gen_reasoning.py
"""
import os
import sys

BASE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, BASE)
import gen_fishbone as G                                       # noqa: E402

PROBLEM = "注塑品质不良"
OUT = "注塑品质不良-要因拆解逻辑.md"

# 一次要因：按俗称「人机料法」排序
# (数据源名, 显示名, 拆解思路一句话)
ORDER = [
    ("人", "人",
     "从**岗位动作**切。人会「不会做」和「没照做」两种失误，加上检查环节「没查出来」，"
     "所以按角色分 —— 作业者、成型技术员、PQC、修模技术员，各自的动作不同，能造成的缺失也不同。"),
    ("设备", "机（设备）",
     "从**作用于塑料的物理量**切：温度、压力、时间、洁净度。产线上真正决定熔体状态的就是四台设备 —— "
     "干燥机（去水分）、模温机（控模温）、模具空腔（成形空间与排气）、成形机（塑化与加压）。"),
    ("材料", "料（材料）",
     "从**合格熔体的四个前提**切：本身没变质、含水率够低、成分够匀、流动能力够。"
     "四条缺任何一条，熔体都填不好型腔，所以按「材质 / 干燥 / 混合材 / 性能」四个条件分。"),
    ("方法", "法（方法）",
     "从**控制链条**切：参数设得对不对（成形条件）、现场照没照做（操作）、"
     "模具养没养到位（模具维护）、把关严不严（检查）。"),
]


def esc(s):
    return str(s).replace("|", "\\|")


def build():
    cats = {c["name"]: c for c in G.CATS}
    missing = [n for n, _d, _t in ORDER if n not in cats]
    if missing:
        raise SystemExit(f"数据源 CATS 中缺少：{missing}")

    n_big = len(ORDER)
    n_mid = n_sm = n_kid = 0
    body = []

    for i, (key, label, idea) in enumerate(ORDER, 1):
        cat = cats[key]
        rows, c_mid, c_sm, c_kid = [], 0, 0, 0
        for gname, _gs, items in cat["groups"]:
            c_mid += 1
            first = True
            for text, star, kids in items:
                c_sm += 1
                c_kid += len(kids)
                t = ("★" if star else "") + esc(text)
                k = "、".join(esc(x[0]) for x in kids) or "—"
                head = f"**{esc(gname)}**" if first else ""
                rows.append(f"| {head} | {t} | {k} |")
                first = False
        n_mid += c_mid
        n_sm += c_sm
        n_kid += c_kid
        body.append(
            f"### 一次要因 {chr(9311 + i)}　{label}\n\n"
            f"> **拆解思路**：{idea}\n\n"
            f"| 二次要因 | 三次要因 | 四次要因 |\n|---|---|---|\n"
            + "\n".join(rows)
            + f"\n\n**本支小计**：二次 {c_mid} 个 · 三次 {c_sm} 条 · 四次 {c_kid} 条\n"
        )

    return "\n".join(body), n_big, n_mid, n_sm, n_kid


DOC = """# {problem} · 要因拆解逻辑

> **一句话**：把「为什么会发生这个问题」一层层往下问，每一步都要讲得出道理，
> 一直问到「**能直接动手改**」或「**能取样验证**」为止。

---

## 一、四个层级，对应鱼骨图的哪个部位

| 层级（本文叫法） | 鱼骨图上的位置 | 通俗理解 | 本次数量 |
|---|---|---|---|
| **问题** | 鱼头（最右侧方框） | 要解决的现象 | 1 |
| **一次要因** | **大骨**（60° 斜线） | 从哪几个大门类去找原因 | **{n_big}** |
| **二次要因** | **中骨**（水平线） | 门类里的具体环节 | **{n_mid}** |
| **三次要因** | **小骨** | 这个环节为什么会出问题 | **{n_sm}** |
| **四次要因** | **小小骨** | 再往下追一层 | **{n_kid}** |

合计 **{total} 条要因**。

> 一次要因的顺序按俗称「**人机料法**」；鱼骨图上为排版把四根大骨分列在主骨上下两侧，
> **图形的排列顺序与这里的先后无关**。

---

## 二、每一层都做同样的四步（核心方法）

| 步骤 | 要做什么 | 关键要求 |
|---|---|---|
| **① 定格** | 锁定上一级的**某一条**要因 | 一次只推一条，不要混着推 |
| **② 建假说** | 问「它在机制上怎么会导致这个问题？」 | **先求全、不求准**，宁多勿漏 |
| **③ 筛选** | 用四条判定过一遍 | 见下方 2.2 |
| **④ 定级** | 留下的即成为下一级要因，回到 ① | 一层一层往下，**不跳级** |

### 2.1 怎么「建假说」——三个角度

| 角度 | 通俗解释 | 例子 |
|---|---|---|
| **原理** | 物理／化学规律 | 材料吸水后高温下会水解 → 分子链断裂 → 流动性变差 |
| **原则** | 工程／管理上的通用要求 | 干燥必须同时满足时间、温度、风量三个条件 |
| **机制** | 设备／流程是怎么运作的 | 干燥机靠加热器＋风机＋定时器协同工作，任何一环失效都会导致干燥不足 |

**实操办法**：拿一个要因，沿「**它由什么构成**／**它靠什么工作**／**它要满足什么要求**」
三个方向各问一遍，问出来的就是候选假说。

### 2.2 怎么「筛选」——四条判定

| 判定 | 说明 | 不合格的例子 |
|---|---|---|
| **可观测** | 现场能看见、能问出来、能追溯 | 「员工心情不好」——看不见也追不到源头 |
| **可测量** | 有数据，或能取样验证 | 「塑料不好」——太笼统，无从取样 |
| **可对策** | 能落到具体动作上 | 「行业不景气」——落不到现场动作 |
| **不重复** | 不与同级其他条目重复，也不跨级重复 | 「温度低」与「溶胶温度低」不同层出现 |

### 2.3 拆到哪一层停

拆到「**能直接采取对策**」或「**能直接取样验证**」为止。再往下就是**对策**，不属于要因分析。

> 例：「材料干燥 → 干燥时间不足 → **定时器异常**」到此为止（可直接校验／更换定时器）；
> 再往下问「定时器为什么会异常」，已经变成设备维修课题，不画进这张图。

---

## 三、走一遍完整链路

```
问题：{problem}
  └ 一次要因：料（材料）          ← 「材料怎么会导致不良？」
      └ 二次要因：材料干燥         ← 机制：塑料必须先干燥到规定含水率
          └ 三次要因：干燥时间不足 ← 「干燥时间怎么会不足？」
              └ 四次要因：定时器异常    ← 停止追问，可直接校验／更换
          └ 三次要因：干燥温度偏低 ← ★ 重点怀疑
```

换一条链路：

```
  └ 一次要因：法（方法）
      └ 二次要因：成形条件
          └ 三次要因：温度
              └ 四次要因：溶胶温度低 ／ 热胶道温度低 ／ 模温低
```

**同一个二次要因下面，条目数不必相等** —— 有的环节只有 1~2 条，有的十几条。
以**机制上的完整性**为准，不为凑数硬加。

---

## 四、全部要因清单

{body}
---

## 五、标注说明

| 标记 | 含义 |
|---|---|
| **★** | **重点要因** —— 假说阶段认为最可能、需优先验证的条目（共 {keys} 条） |

★ 只是**怀疑优先级**，不是「已确认的真因」。真因必须靠现场数据／试验验证后才能定。

---

## 六、适用范围说明

1. 本清单以「**注塑件缺料（短射）**」这一最典型的不良为切入点收集，
   条目在机制层面**同样适用于其他注塑不良**（缩水、飞边、烧焦、尺寸超差等）。
2. 若要覆盖**全部不良类型**，按本文第二节的四步循环继续补即可 ——
   方法不变，只是「建假说」时换一个现象去问。
3. **层级归属一律以现有鱼骨图为准**（数据来自原图 1:1 提取），本文只做语言与结构的整理，未增删条目。

---

_本文件由 `gen_reasoning.py` 从 `gen_fishbone.py` 的数据源自动生成，改数据后重跑即可同步。_
"""


def main():
    body, n_big, n_mid, n_sm, n_kid = build()
    keys = sum(1 for c in G.CATS for _g, _s, items in c["groups"]
               for _t, star, _k in items if star)
    total = n_big + n_mid + n_sm + n_kid
    doc = DOC.format(problem=PROBLEM, body=body, n_big=n_big, n_mid=n_mid,
                     n_sm=n_sm, n_kid=n_kid, total=total, keys=keys)
    p = os.path.join(BASE, OUT)
    with open(p, "w", encoding="utf-8") as f:
        f.write(doc)
    print(f"OK -> {OUT}  {len(doc)} 字符")
    print(f"层级: 一次 {n_big} · 二次 {n_mid} · 三次 {n_sm} · 四次 {n_kid}  = 共 {total} 条")
    print(f"★ 重点要因: {keys} 条")
    # 自查：每个一次要因都在正文出现
    for _n, label, _t in ORDER:
        assert f"　{label}" in body, f"{label} 未写入正文"
    print("自查: 四支一次要因均已写入 OK")


if __name__ == "__main__":
    main()
